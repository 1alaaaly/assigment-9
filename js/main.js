// ======================================================
// WAIT UNTIL HTML IS LOADED
// ======================================================

document.addEventListener("DOMContentLoaded", function () {

    // ==================================================
    // VARIABLES
    // ==================================================

    let currentRecipe = 0;

    let currentTab = "ingredients";

    let saved = false;


    // ==================================================
    // ELEMENTS
    // ==================================================

    const recipeImage =
        document.getElementById("recipeImage");

    const recipeTitle =
        document.getElementById("recipeTitle");

    const recipeDescription =
        document.getElementById("recipeDescription");

    const difficulty =
        document.getElementById("difficulty");

    const category =
        document.getElementById("category");

    const rating =
        document.getElementById("rating");

    const reviews =
        document.getElementById("reviews");

    const prepTime =
        document.getElementById("prepTime");

    const cookTime =
        document.getElementById("cookTime");

    const servings =
        document.getElementById("servings");

    const warningBox =
        document.getElementById("warningBox");

    const tabPanel =
        document.getElementById("tabPanel");

    const saveBtn =
        document.getElementById("saveBtn");

    const nextRecipeBtn =
        document.getElementById("nextRecipe");

    const shareBtn =
        document.getElementById("shareBtn");

    const tabs =
        document.querySelectorAll(".tab-btn");


    // ==================================================
    // CHECK BUTTON
    // ==================================================

    if (!nextRecipeBtn) {

        console.error(
            "Try Another Recipe button was not found!"
        );

        return;
    }


    // ==================================================
    // RENDER TAB
    // ==================================================

    function renderTab() {

        const recipe =
            recipes[currentRecipe];


        // =================================================
        // INGREDIENTS
        // =================================================

        if (currentTab === "ingredients") {

            tabPanel.innerHTML = `

                <div class="ingredients-box">

                    ${recipe.ingredients.map(
                        function (ingredient, index) {

                            return `

                                <div class="ingredient-row">

                                    <div class="number">
                                        ${index + 1}
                                    </div>

                                    <span>
                                        ${ingredient}
                                    </span>

                                </div>

                            `;
                        }
                    ).join("")}

                </div>

            `;
        }


        // =================================================
        // INSTRUCTIONS
        // =================================================

        else if (currentTab === "instructions") {

            tabPanel.innerHTML = `

                <div class="instruction-list">

                    ${recipe.instructions.map(
                        function (instruction, index) {

                            return `

                                <div class="instruction-item">

                                    <div class="step">
                                        ${index + 1}
                                    </div>

                                    <div class="instruction-text">
                                        ${instruction}
                                    </div>

                                </div>

                            `;
                        }
                    ).join("")}

                </div>

            `;
        }


        // =================================================
        // NUTRITION
        // =================================================

        else if (currentTab === "nutrition") {

            tabPanel.innerHTML = `

                <div class="nutrition-grid">

                    ${recipe.nutrition.map(
                        function (nutrition) {

                            return `

                                <div class="nutrition-card">

                                    <div class="nutrition-icon">

                                        <i class="${nutrition[2]}"></i>

                                    </div>

                                    <span>
                                        ${nutrition[0]}
                                    </span>

                                    <strong>
                                        ${nutrition[1]}
                                    </strong>

                                </div>

                            `;
                        }
                    ).join("")}

                </div>

            `;
        }


        // =================================================
        // CHEF'S TIPS
        // =================================================

        else if (currentTab === "tips") {

            tabPanel.innerHTML = `

                <div class="chef-tips">

                    ${recipe.tips.map(
                        function (tip) {

                            return `

                                <div class="tip-item">

                                    <div class="tip-icon">

                                        <i class="bi bi-check-lg"></i>

                                    </div>

                                    <span>
                                        ${tip}
                                    </span>

                                </div>

                            `;
                        }
                    ).join("")}

                </div>

            `;
        }

    }


    // ==================================================
    // RENDER RECIPE
    // ==================================================

    function renderRecipe() {

        const recipe =
            recipes[currentRecipe];


        // IMAGE

        recipeImage.src =
            recipe.image;

        recipeImage.alt =
            recipe.title;


        // TITLE

        recipeTitle.textContent =
            recipe.title;


        // DESCRIPTION

        recipeDescription.textContent =
            recipe.description;


        // DIFFICULTY

        difficulty.textContent =
            recipe.difficulty;


        // CATEGORY

        category.textContent =
            recipe.category;


        // RATING

        rating.textContent =
            recipe.rating;


        // REVIEWS

        reviews.textContent =
            recipe.reviews;


        // PREP TIME

        prepTime.textContent =
            recipe.prep;


        // COOK TIME

        cookTime.textContent =
            recipe.cook;


        // SERVINGS

        servings.textContent =
            recipe.servings;


        // WARNING

        if (recipe.warning === true) {

            warningBox.style.display = "flex";

        } else {

            warningBox.style.display = "none";

        }


        // RESET BOOKMARK

        saved = false;

        if (saveBtn) {

            saveBtn.classList.remove("saved");

            saveBtn.innerHTML =
                '<i class="bi bi-bookmark-fill"></i>';

        }


        // RENDER CURRENT TAB

        renderTab();

    }


    // ==================================================
    // TAB BUTTONS
    // ==================================================

    tabs.forEach(function (tab) {

        tab.addEventListener(
            "click",
            function () {

                // Remove active
                tabs.forEach(function (item) {

                    item.classList.remove("active");

                });


                // Add active
                this.classList.add("active");


                // Get selected tab
                currentTab =
                    this.dataset.tab;


                // Render selected tab
                renderTab();

            }
        );

    });


    // ==================================================
    // TRY ANOTHER RECIPE
    // ==================================================

    nextRecipeBtn.addEventListener(
        "click",
        function () {

            console.log(
                "Try Another Recipe clicked"
            );


            // Go to next recipe
            currentRecipe++;


            // Back to first recipe
            if (
                currentRecipe >= recipes.length
            ) {

                currentRecipe = 0;

            }


            // Always start from Ingredients
            currentTab =
                "ingredients";


            // Remove active from all tabs
            tabs.forEach(function (tab) {

                tab.classList.remove("active");

            });


            // Activate Ingredients
            const ingredientsTab =
                document.querySelector(
                    '[data-tab="ingredients"]'
                );


            if (ingredientsTab) {

                ingredientsTab.classList.add("active");

            }


            // Update complete recipe
            renderRecipe();

        }
    );


    // ==================================================
    // SAVE BUTTON
    // ==================================================

    if (saveBtn) {

        saveBtn.addEventListener(
            "click",
            function () {

                saved = !saved;


                if (saved) {

                    saveBtn.classList.add("saved");

                    saveBtn.innerHTML =
                        '<i class="bi bi-bookmark-check-fill"></i>';

                    showToast(
                        "Recipe saved!"
                    );

                } else {

                    saveBtn.classList.remove("saved");

                    saveBtn.innerHTML =
                        '<i class="bi bi-bookmark-fill"></i>';

                    showToast(
                        "Recipe removed!"
                    );

                }

            }
        );

    }


    // ==================================================
    // SHARE BUTTON
    // ==================================================

    if (shareBtn) {

        shareBtn.addEventListener(
            "click",
            async function () {

                const recipe =
                    recipes[currentRecipe];


                if (navigator.share) {

                    try {

                        await navigator.share({

                            title:
                                recipe.title,

                            text:
                                recipe.description,

                            url:
                                window.location.href

                        });

                    } catch (error) {

                        console.log(
                            "Share cancelled"
                        );

                    }

                } else {

                    try {

                        await navigator.clipboard.writeText(
                            window.location.href
                        );

                        showToast(
                            "Recipe link copied!"
                        );

                    } catch (error) {

                        showToast(
                            "Could not copy link."
                        );

                    }

                }

            }
        );

    }


    // ==================================================
    // HEADER BOOKMARK
    // ==================================================

    const bookmarkHeader =
        document.getElementById(
            "bookmarkHeader"
        );


    if (bookmarkHeader) {

        bookmarkHeader.addEventListener(
            "click",
            function () {

                if (saved) {

                    showToast(
                        "This recipe is saved!"
                    );

                } else {

                    showToast(
                        "No saved recipe yet."
                    );

                }

            }
        );

    }


    // ==================================================
    // HISTORY BUTTON
    // ==================================================

    const historyBtn =
        document.getElementById(
            "historyBtn"
        );


    if (historyBtn) {

        historyBtn.addEventListener(
            "click",
            function () {

                showToast(
                    "Recipe history clicked."
                );

            }
        );

    }


    // ==================================================
    // SETTINGS BUTTON
    // ==================================================

    const settingsBtn =
        document.getElementById(
            "settingsBtn"
        );


    if (settingsBtn) {

        settingsBtn.addEventListener(
            "click",
            function () {

                showToast(
                    "Settings clicked."
                );

            }
        );

    }


    // ==================================================
    // TOAST
    // ==================================================

    function showToast(message) {

        const toastMessage =
            document.getElementById(
                "toastMessage"
            );


        const toastElement =
            document.getElementById(
                "liveToast"
            );


        if (!toastElement) {

            return;

        }


        if (toastMessage) {

            toastMessage.textContent =
                message;

        }


        if (
            typeof bootstrap !== "undefined" &&
            bootstrap.Toast
        ) {

            const toast =
                bootstrap.Toast.getOrCreateInstance(
                    toastElement,
                    {
                        delay: 2200
                    }
                );

            toast.show();

        }

    }


    // ==================================================
    // INITIAL LOAD
    // ==================================================

    renderRecipe();

});